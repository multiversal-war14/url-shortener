# --------------------------------------------------
# Database configuration
#
# Default: SQLite for local development.
# Production: set DB_ENGINE=postgresql and the
# POSTGRES_* environment variables.
# --------------------------------------------------

DB_ENGINE = os.environ.get("DB_ENGINE", "sqlite").lower()

if DB_ENGINE == "postgresql":
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.environ.get("POSTGRES_DB", "urlshortener"),
            "USER": os.environ.get("POSTGRES_USER", "urlshortener"),
            "PASSWORD": os.environ.get("POSTGRES_PASSWORD", ""),
            "HOST": os.environ.get("POSTGRES_HOST", "localhost"),
            "PORT": os.environ.get("POSTGRES_PORT", "5432"),
            "CONN_MAX_AGE": 60,
            "CONN_HEALTH_CHECKS": True,
        }
    }

    if not DATABASES["default"]["PASSWORD"]:
        raise RuntimeError(
            "POSTGRES_PASSWORD must be configured for PostgreSQL."
        )

elif DB_ENGINE == "sqlite":
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
            "OPTIONS": {
                "timeout": 60,
            },
        }
    }

else:
    raise RuntimeError(
        "DB_ENGINE must be either 'sqlite' or 'postgresql'."
    )


